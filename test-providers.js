/* 通道契约测试：用 stub fetch 断言各 provider 的请求形状（URL / 头 / body）与响应解析。
   不需要真实密钥，可直接在 CI 里跑。
   用法：npm run build && node test-providers.js
   加载的是打包产物 dist/background/index.js（IIFE，全局名 SelectTransBackground）。 */
const fs = require('fs');
const vm = require('vm');

let captured = null;
const sandbox = {
  fetch: async () => { throw new Error('fetch 未设置'); },
  console,
  URLSearchParams,
  chrome: { storage: { local: { get: async () => ({}), set: async () => {} } } },
  setTimeout,
  clearTimeout,
};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(__dirname + '/dist/background/index.js', 'utf8'), sandbox);

/** 打包产物暴露出来的 background 接口 */
const api = sandbox.SelectTransBackground;

let fail = 0;
const ok = (c, m) => { if (c) console.log('  ok  :', m); else { console.error('  FAIL:', m); fail = 1; } };

/** 把 fetch 换成返回固定响应的桩，并记录请求 */
function stub(response, status) {
  captured = null;
  sandbox.fetch = async (url, opts) => {
    captured = { url, opts, body: opts && opts.body ? JSON.parse(opts.body) : null };
    return { ok: (status || 200) < 400, status: status || 200, json: async () => response };
  };
}

const SENT = 'The initial scaffold was generated by Codex CLI using GPT-5.';

(async () => {
  /* ---------------- 腾讯混元 HY-MT2 已移除 ---------------- */
  console.log('\n== 腾讯混元 HY-MT2 / 已从通道表移除 ==');
  let tcGone = null;
  try {
    await api.runProvider('tencent', { text: SENT, targetLang: 'zh-CN' }, () => {}, {});
  } catch (e) { tcGone = e.message; }
  ok(tcGone === 'UNKNOWN_PROVIDER', 'tencent 不再被 runProvider 接受：' + tcGone);

  console.log('\n== 中文原文自动改译英语 ==');
  ok(api.effectiveTargetLang('你好世界', 'zh-CN') === 'en', '中文原文 + 中文目标 → en');
  ok(api.effectiveTargetLang('Hello world', 'zh-CN') === 'zh-CN', '英文原文不翻转');
  ok(api.effectiveTargetLang('我想买一台 iPhone', 'zh-CN') === 'en', '中英混排仍按中文判定');
  ok(api.effectiveTargetLang('This is 中文', 'zh-CN') === 'zh-CN', '英文为主的中英混排不翻转');
  ok(api.effectiveTargetLang('你好', 'en') === 'en', '目标已是英语时保持不变');

  sandbox.chrome.storage.local.get = async (k) => (k === 'settings'
    ? { settings: { aiEnabled: true, deepl: { apiKey: 'k:fx' } } }
    : {});
  stub({ translations: [{ text: 'The weather is nice today.' }] });
  const zhRes = await api.aiTranslate(
    { text: '今天天气不错，我们出去走走吧。', targetLang: 'zh-CN', provider: 'deepl' }, null, {},
  );
  ok(captured.body.target_lang === 'EN-US', '中文原文时 DeepL 目标语言翻成 EN-US：' + captured.body.target_lang);
  ok(zhRes.text === 'The weather is nice today.', '译文正常返回：' + zhRes.text);
  sandbox.chrome.storage.local.get = async () => ({});

  /* ---------------- DeepL ---------------- */
  console.log('\n== DeepL / 请求形状 ==');
  stub({ translations: [{ detected_source_language: 'EN', text: '最初的脚手架。' }] });
  const dlFree = { deepl: { apiKey: 'abc-123:fx' } };
  await api.runProvider('deepl', { text: SENT, targetLang: 'zh-CN' }, () => {}, dlFree);
  ok(captured.url === 'https://api-free.deepl.com/v2/translate', 'Free Key（:fx）走 api-free：' + captured.url);
  ok(captured.opts.headers.Authorization === 'DeepL-Auth-Key abc-123:fx', '认证头 DeepL-Auth-Key');
  ok(Array.isArray(captured.body.text), 'text 以数组提交（支持多段按序返回）');
  ok(captured.body.target_lang === 'ZH', '简体中文映射为 ZH：' + captured.body.target_lang);

  stub({ translations: [{ text: 'A' }, { text: 'B' }] });
  const dlPro = { deepl: { apiKey: 'pro-key-999' } };
  const joined = await api.runProvider('deepl', { text: SENT, targetLang: 'en' }, () => {}, dlPro);
  ok(captured.url === 'https://api.deepl.com/v2/translate', '非 :fx 走 Pro：' + captured.url);
  ok(joined === 'AB', '多段译文按序拼接：' + joined);

  /* ---------------- Microsoft Translator（Azure） ---------------- */
  console.log('\n== Microsoft Translator / 请求形状 ==');
  stub([{ translations: [{ text: '最初的脚手架。', to: 'zh-Hans' }] }]);
  await api.runProvider(
    'azure', { text: SENT, targetLang: 'zh-CN' }, () => {},
    { azure: { apiKey: 'az-key-1', region: 'eastasia' } },
  );
  ok(captured.url === 'https://api.cognitive.microsofttranslator.com/translate?api-version=3.0&to=zh-Hans',
     'URL 与语言码（zh-Hans）：' + captured.url);
  ok(captured.opts.headers['Ocp-Apim-Subscription-Key'] === 'az-key-1', '订阅密钥头');
  ok(captured.opts.headers['Ocp-Apim-Region'] === 'eastasia', '区域头');
  ok(Array.isArray(captured.body) && captured.body[0].Text === SENT, 'body 为 [{Text}]');
  ok(!captured.url.includes('from='), '不传 from，交给 Azure 自动检测');

  stub([{ translations: [{ text: 'A' }] }, { translations: [{ text: 'B' }] }]);
  const azOut = await api.runProvider(
    'azure', { text: SENT, targetLang: 'zh-TW' }, () => {},
    { azure: { apiKey: 'k', region: 'global' } },
  );
  ok(azOut === 'AB', '多段译文按序拼接：' + azOut);
  ok(captured.url.endsWith('to=zh-Hant'), '繁体映射为 zh-Hant');

  /* ---------------- Google Cloud Translation ---------------- */
  console.log('\n== Google Cloud Translation / 请求形状 ==');
  stub({ data: { translations: [{ translatedText: '谷歌译文' }] } });
  const ggOut = await api.runProvider(
    'google', { text: SENT, targetLang: 'zh-CN' }, () => {},
    { google: { apiKey: 'AIzaTEST' } },
  );
  ok(captured.url.indexOf('https://translation.googleapis.com/language/translate/v2') === 0,
     '走 v2 端点：' + captured.url.split('?')[0]);
  ok(captured.url.includes('key=AIzaTEST'), 'API Key 走 query：' + captured.url.split('?')[1]);
  ok(Array.isArray(captured.body.q), 'q 以数组提交');
  ok(captured.body.target === 'zh-CN' && captured.body.format === 'text', 'target/format 正确');
  ok(ggOut === '谷歌译文', '解析 data.translations[].translatedText：' + ggOut);

  /* ---------------- LibreTranslate ---------------- */
  console.log('\n== LibreTranslate / 请求形状 ==');
  stub({ translatedText: '开源译文' });
  const lbOut = await api.runProvider(
    'libre', { text: SENT, targetLang: 'zh-CN' }, () => {},
    { libre: { baseUrl: 'http://localhost:5000' } },
  );
  ok(captured.url === 'http://localhost:5000/translate', '自建地址拼接 /translate：' + captured.url);
  ok(captured.body.q === SENT && captured.body.target === 'zh', 'body 的 q 与 target（中文码 zh）');
  ok(captured.body.source === 'en', '源语言按字符启发式给出：' + captured.body.source);
  ok(!('api_key' in captured.body), '没填 Key 时不带 api_key 字段');
  ok(lbOut === '开源译文', '解析 translatedText：' + lbOut);

  stub({ translatedText: 'X' });
  await api.runProvider(
    'libre', { text: SENT, targetLang: 'zh-CN' }, () => {},
    { libre: { baseUrl: 'https://libretranslate.com/', apiKey: 'lbk' } },
  );
  ok(captured.url === 'https://libretranslate.com/translate', '末尾斜杠归一化：' + captured.url);
  ok(captured.body.api_key === 'lbk', '填了 Key 就带上 api_key');

  /* ---------------- 并列对照（aiTranslateParallel） ---------------- */
  console.log('\n== 并列对照 / 失败不互相牵连 ==');
  const evFail = [];
  await api.aiTranslateParallel(
    { text: 'Hello world', targetLang: 'zh-CN', providers: ['deepl', 'google'] },
    (ev) => evFail.push(ev),
  );
  const errs = evFail.filter((e) => e.phase === 'error');
  ok(errs.length === 2, '两个通道各自报错：' + errs.length);
  ok(errs.some((e) => e.code === 'DEEPL_NO_KEY') && errs.some((e) => e.code === 'GOOGLE_NO_KEY'),
     '错误码按通道区分：' + errs.map((e) => e.code).join(' / '));
  ok(!evFail.some((e) => e.phase === 'done'),
     '并列模式不做免费机器翻译兜底（否则两列会显示同一个结果）');
  ok(evFail.every((e) => typeof e.index === 'number' && typeof e.provider === 'string'),
     '每条事件带 index 与 provider，UI 才能定位列');

  console.log('\n== 并列对照 / 双通道成功 ==');
  sandbox.chrome.storage.local.get = async (k) => (k === 'settings'
    ? { settings: { aiEnabled: true, fallbackEnabled: true, deepl: { apiKey: 'kk:fx' }, google: { apiKey: 'gk' } } }
    : {});
  const hits = [];
  sandbox.fetch = async (url) => {
    hits.push(url);
    if (url.indexOf('deepl.com') >= 0) {
      return { ok: true, status: 200, json: async () => ({ translations: [{ text: 'DEEPL 译文' }] }) };
    }
    return { ok: true, status: 200, json: async () => ({ data: { translations: [{ translatedText: 'GOOGLE 译文' }] } }) };
  };
  const evOk = [];
  await api.aiTranslateParallel(
    { text: 'Hello world', targetLang: 'zh-CN', providers: ['deepl', 'google'] },
    (ev) => evOk.push(ev),
  );
  const dones = evOk.filter((e) => e.phase === 'done');
  ok(dones.length === 2, '两个通道都拿到结果：' + dones.length);
  ok(dones.some((d) => d.provider === 'deepl' && d.text === 'DEEPL 译文'), 'DeepL 的译文归到 deepl 列');
  ok(dones.some((d) => d.provider === 'google' && d.text === 'GOOGLE 译文'), 'Google 的译文归到 google 列');
  ok(hits.length === 2, '两路请求都发出：' + hits.length);

  console.log('\n== 并列对照 / LibreTranslate 也参与并排 ==');
  sandbox.chrome.storage.local.get = async (k) => (k === 'settings'
    ? { settings: { aiEnabled: true, libre: { baseUrl: '' } } }
    : {});
  const evLb = [];
  await api.aiTranslateParallel(
    { text: 'Hello world', targetLang: 'zh-CN', providers: ['libre', 'deepl'] },
    (ev) => evLb.push(ev),
  );
  ok(evLb.some((e) => e.provider === 'libre' && e.phase === 'error' && e.code === 'LIBRE_NO_BASEURL'),
     'libre 作为独立一列参与并排');
  ok(evLb.some((e) => e.provider === 'deepl' && e.phase === 'error' && e.code === 'DEEPL_NO_KEY'),
     '其余远程通道照常独立跑');
  sandbox.chrome.storage.local.get = async () => ({});

  console.log('\n== 并列对照 / 单通道数组也要独立 ==');
  sandbox.chrome.storage.local.get = async () => ({});   // 清掉上一段塞的密钥
  let single = null;
  sandbox.fetch = async () => { throw new Error('不该发请求：缺密钥应直接报错'); };
  await api.aiTranslateParallel(
    { text: 'Hello world', targetLang: 'zh-CN', providers: ['deepl'] },
    (ev) => { single = ev; },
  );
  ok(single && single.provider === 'deepl' && single.phase === 'error' && single.code === 'DEEPL_NO_KEY',
     '只有一个远程通道时也走并列，不回落到单通道兜底：' + (single && single.code));

  console.log('\n== 并列对照 / background 不接 chrome-ai ==');
  const evBad = [];
  await api.aiTranslateParallel(
    { text: 'Hello world', targetLang: 'zh-CN', providers: ['chrome-ai', 'deepl'] },
    (ev) => evBad.push(ev),
  );
  ok(!evBad.some((e) => e.provider === 'chrome-ai'),
     'chrome-ai 不由 background 处理（它在页面上下文单独起一路）');
  ok(evBad.some((e) => e.provider === 'deepl'), 'deepl 仍由 background 处理');

  console.log(fail ? '\n有失败项' : '\n全部通过');
  process.exitCode = fail;
})();
